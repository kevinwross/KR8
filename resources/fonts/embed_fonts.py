from pathlib import Path

root = Path(__file__).resolve().parent
output = root.parent.parent / "src" / "resources" / "embedded_fonts.cpp"
header = root.parent.parent / "src" / "resources" / "embedded_fonts.hpp"

fonts = [
    ("kInterRegular", "Inter-Regular-Subset.ttf"),
    ("kInterBold", "Inter-Bold-Subset.ttf"),
    ("kJetBrainsRegular", "JetBrainsMono-Regular-Subset.ttf"),
    ("kJetBrainsBold", "JetBrainsMono-Bold-Subset.ttf"),
]

header.write_text(
    """#pragma once

#include <cstdint>
#include <span>

namespace kr16::ui {

struct EmbeddedFonts {
    std::span<const std::uint8_t> ui_regular;
    std::span<const std::uint8_t> ui_bold;
    std::span<const std::uint8_t> mono_regular;
    std::span<const std::uint8_t> mono_bold;
};

EmbeddedFonts embedded_fonts();

}  // namespace kr16::ui
""",
    encoding="utf-8",
)

lines = [
    "// Generated by resources/fonts/embed_fonts.py; do not edit by hand.",
    '#include "resources/embedded_fonts.hpp"',
    "",
    "#include <array>",
    "",
    "namespace kr16::ui {",
    "namespace {",
]
for name, filename in fonts:
    data = (root / filename).read_bytes()
    lines.append(f"constexpr std::array<std::uint8_t, {len(data)}> {name} = {{")
    for i in range(0, len(data), 16):
        chunk = data[i : i + 16]
        lines.append("    " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    lines.append("};")
    lines.append("")
lines.append("}  // namespace")
lines.append("")
lines.append("EmbeddedFonts embedded_fonts() {")
lines.append("    return EmbeddedFonts{kInterRegular, kInterBold,")
lines.append("                        kJetBrainsRegular, kJetBrainsBold};")
lines.append("}")
lines.append("")
lines.append("}  // namespace kr16::ui")
output.write_text("\n".join(lines) + "\n", encoding="utf-8")
print(output)
